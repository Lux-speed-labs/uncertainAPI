"""Portable integration specifications.

These models are intentionally framework- and provider-neutral. They are data
contracts that can be persisted in a database, serialized to JSON, generated by
a private compiler, or constructed manually by OSS users.
"""

from __future__ import annotations

from typing import Any

from pydantic import BaseModel, Field


class SourceSpec(BaseModel):
    """Description of where and how data should be acquired."""

    type: str = Field(description="Adapter discriminator, e.g. http_json, graphql, html")
    endpoint: str = Field(description="URL or provider-specific source endpoint")
    method: str = "GET"
    headers: dict[str, str] = Field(default_factory=dict)
    params: dict[str, Any] = Field(default_factory=dict)
    body: Any | None = None
    auth_ref: str | None = Field(
        default=None,
        description="Opaque reference to credentials; never embed secrets in a plan",
    )
    options: dict[str, Any] = Field(default_factory=dict)


class ContractSpec(BaseModel):
    """Stable downstream data contract."""

    name: str
    version: str
    schema: dict[str, Any] = Field(description="Language-neutral JSON Schema")
    metadata: dict[str, Any] = Field(default_factory=dict)


class MappingSpec(BaseModel):
    """Deterministic rules that map a source payload to a contract."""

    version: str = "1"
    records_selector: str | None = None
    fields: dict[str, str] = Field(default_factory=dict)
    transforms: dict[str, Any] = Field(default_factory=dict)
    metadata: dict[str, Any] = Field(default_factory=dict)


class IntegrationSpec(BaseModel):
    """Binding of source, contract, mapping, and execution policy."""

    source: SourceSpec
    contract: ContractSpec
    mapping: MappingSpec
    policies: dict[str, Any] = Field(default_factory=dict)
    metadata: dict[str, Any] = Field(default_factory=dict)
